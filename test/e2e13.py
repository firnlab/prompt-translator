def idle(pg, ms=20000): pg.wait_for_function("AI.running.size === 0", timeout=ms); pg.wait_for_timeout(150)
def new_ctx(b, w=1440, h=950, scheme="dark"):
    ctx = b.new_context(viewport={"width": w, "height": h}, color_scheme=scheme)
